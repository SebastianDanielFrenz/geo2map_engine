// Reference generator for tests/world/test_view_streamer.cpp and test_buildings.cpp: runs racing_game's own view
// functions, TerrainViewStreamer, diff-order helpers and extract_buildings (5a3baed, extracted verbatim by
// extract_view_ref.sh) over the inputs of view_test_data.h and building_test_data.h and prints view_pins.inc, then
// building_pins.inc after a "// ---- building_pins.inc" line. Build/run: see tests/world/CMakeLists.txt.
#include "building_test_data.h"
#include "view_test_data.h"

#include "rg/buildings.h"
#include "rg/lod_settings.h"
#include "rg/terrain_stream.h"
#include "rg/terrain_view_streamer.h"
#include "rg/world_terrain.h"

#include <cstdio>

namespace {
void print(const std::vector<g2m_view_test::Pin>& pins) {
    for (const auto& p : pins)
        std::printf("{\"%s\", %llu, 0x%016llxull},\n", p.name.c_str(), static_cast<unsigned long long>(p.count),
                    static_cast<unsigned long long>(p.hash));
}
} // namespace

int main() {
    using namespace g2m_view_test;
    std::printf("// Generated by tests/world/refgen/refgen_view.cpp from racing_game 5a3baed's own world_terrain.cpp view\n"
                "// functions, terrain_view_streamer.cpp, terrain_stream.cpp and lod_settings.cpp over view_test_data.h. Do not edit.\n"
                "// {name, count, hash}; diff counts are added * 1e6 + removed * 1e3 + replaced.\n");
    print(build_pins<rg::TerrainViewSource, rg::RenderChunk>(
        [](double x, double y, const g2m::mesh::LodParams& p, double e0, double n0, std::vector<ChunkKey>& keys) {
            rg::select_view_keys(x, y, p, e0, n0, keys);
        },
        [](const std::vector<ChunkKey>& keys, const rg::TerrainViewSource& s, unsigned threads, std::vector<rg::RenderChunk>& out) {
            rg::build_render_chunks(keys, s.lookup, s.ctx, s.e0, s.n0, threads, out, nullptr, s.class_lookup, s.surfaces,
                                    s.carve_state);
        }));
    const auto one = streamer_pins<rg::TerrainViewSource, rg::TerrainViewStreamer, rg::RenderChunk, rg::TerrainViewDiff>(1);
    const auto three = streamer_pins<rg::TerrainViewSource, rg::TerrainViewStreamer, rg::RenderChunk, rg::TerrainViewDiff>(3);
    for (std::size_t i = 0; i < one.size(); ++i)
        if (one[i].hash != three[i].hash || one[i].count != three[i].count) {
            std::fprintf(stderr, "streamer pins differ between 1 and 3 build threads at %s\n", one[i].name.c_str());
            return 1;
        }
    print(one);
    print(order_pins<rg::RenderChunk>(
        [](const ChunkKey& k, double e0, double n0, double px, double py, double vx, double vy) {
            return rg::chunk_time_to_reach_s(k, e0, n0, px, py, vx, vy);
        },
        [](double base, double speed) { return rg::reselect_distance_for_speed(base, speed); },
        [](std::vector<rg::RenderChunk>& c, double e0, double n0, double px, double py, double vx, double vy) {
            rg::sort_adds_by_urgency(c, e0, n0, px, py, vx, vy);
        },
        [](const g2m::RenderRoadLod* a, const g2m::RenderRoadLod* b, int max_level) {
            return rg::changed_road_lod_levels(a, b, max_level);
        }));

    std::printf("// ---- building_pins.inc\n"
                "// Generated by tests/world/refgen/refgen_view.cpp from racing_game 5a3baed's own buildings.cpp over\n"
                "// building_test_data.h's cases (fixture tiles without buildings left out). Do not edit. {case, buildings, hash}\n");
    for (const auto& c : g2m_building_test::cases()) {
        const auto b = rg::extract_buildings(c.tile, c.key, c.min_height, c.fallback, c.storey, &g2m_building_test::ground);
        if (b.empty() && c.name.rfind("scene", 0) != 0) continue; // fixture tiles without buildings: the test expects none
        std::printf("{\"%s\", %zu, 0x%016llxull},\n", c.name.c_str(), b.size(),
                    static_cast<unsigned long long>(g2m_building_test::hash_buildings(b)));
    }
    return 0;
}
