// Reference generator for tests/world/test_road_meshes.cpp: runs racing_game's own build_road_decks / road_deck_height /
// build_road_visual (945455a, extracted verbatim by extract_mesh_ref.sh) over the cases of road_mesh_test_data.h and
// prints road_mesh_pins.inc. Build/run: see tests/world/CMakeLists.txt. A case without separation runs the game with
// clearance 1e9 / margin 0 / reach 0 (no approach deck can form), which equals 0c027dc's output (the pins of those
// cases were first recorded from 0c027dc and are unchanged).
#include "road_mesh_test_data.h"

#include "rg/road_structures.h"
#include "rg/road_visual.h"

#include <cstdio>

int main() {
    using namespace g2m_mesh_test;
    const auto cases = mesh_cases();
    std::printf("// Generated by tests/world/refgen/refgen_meshes.cpp from racing_game's own road_structures.cpp and road_visual.cpp\n"
                "// (945455a; the cases without separation equal 0c027dc's output) over road_mesh_test_data.h's cases. Do not edit.\n"
                "// {case, decks, deck hash, deck start_ref hash, ribbon vertices, ribbon indices, ribbon hash}  // bridges tunnels inferred\n");
    for (const auto& c : cases) {
        rg::RoadSeparation sep;
        if (!c.separated) {
            sep.clearance_m = 1e9;
            sep.margin_m = 0;
            sep.approach_reach_m = 0;
        }
        const auto decks = rg::build_road_decks(c.tile, sep);
        g2m::Fnv1a64 h, refs;
        int bridges = 0, tunnels = 0, inferred = 0;
        for (const auto& d : decks) {
            hash_deck(h, *d, [](const rg::RoadDeck& deck, double s, double t) { return rg::road_deck_height(deck, s, t); });
            refs.u32(d->start_ref);
            inferred += d->inferred;
            tunnels += !d->inferred && d->tunnel_floor;
            bridges += !d->inferred && !d->tunnel_floor;
        }
        const auto ribbon = rg::build_road_visual(c.tile, c.key, [&](double e, double n) { return case_ground(c, e, n); }, c.lift, sep);
        std::printf("{\"%s\", %zu, 0x%016llxull, 0x%016llxull, %zu, %zu, 0x%016llxull},  // %d %d %d\n", c.name.c_str(), decks.size(),
                    static_cast<unsigned long long>(h.value()), static_cast<unsigned long long>(refs.value()), ribbon.vertices.size(),
                    ribbon.indices.size(), static_cast<unsigned long long>(hash_ribbon(ribbon)), bridges, tunnels, inferred);
    }
    return 0;
}
