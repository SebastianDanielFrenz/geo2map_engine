// Reference generator for tests/world/test_road_meshes.cpp: runs racing_game 0c027dc's own build_road_decks /
// road_deck_height / build_road_visual (extracted verbatim by extract_mesh_ref.sh) over the cases of
// road_mesh_test_data.h and prints road_mesh_pins.inc. Build/run: see tests/world/CMakeLists.txt.
#include "road_mesh_test_data.h"

#include "rg/road_structures.h"
#include "rg/road_visual.h"

#include <cstdio>

int main() {
    using namespace g2m_mesh_test;
    const auto cases = mesh_cases();
    std::printf("// Generated by tests/world/refgen/refgen_meshes.cpp from racing_game 0c027dc's own road_structures.cpp and\n"
                "// road_visual.cpp over road_mesh_test_data.h's cases. Do not edit by hand.\n"
                "// {case, decks, deck hash, ribbon vertices, ribbon indices, ribbon hash}  // bridges tunnels inferred\n");
    for (const auto& c : cases) {
        const auto decks = rg::build_road_decks(c.tile);
        g2m::Fnv1a64 h;
        int bridges = 0, tunnels = 0, inferred = 0;
        for (const auto& d : decks) {
            hash_deck(h, *d, [](const rg::RoadDeck& deck, double s, double t) { return rg::road_deck_height(deck, s, t); });
            inferred += d->inferred;
            tunnels += !d->inferred && d->tunnel_floor;
            bridges += !d->inferred && !d->tunnel_floor;
        }
        const auto ribbon = rg::build_road_visual(c.tile, c.key, [&](double e, double n) { return case_ground(c, e, n); }, c.lift);
        std::printf("{\"%s\", %zu, 0x%016llxull, %zu, %zu, 0x%016llxull},  // %d %d %d\n", c.name.c_str(), decks.size(),
                    static_cast<unsigned long long>(h.value()), ribbon.vertices.size(), ribbon.indices.size(),
                    static_cast<unsigned long long>(hash_ribbon(ribbon)), bridges, tunnels, inferred);
    }
    return 0;
}
