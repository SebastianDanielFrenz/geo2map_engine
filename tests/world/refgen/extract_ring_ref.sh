#!/usr/bin/env bash
# Records tests/world/ring_pins.inc: runs racing_game 5a3baed's own game/scripts/road_stream.gd and
# building_stream.gd (extracted VERBATIM from the commit into a throw-away Godot project, with one edit: the
# statistics-only RgRenderFocus.grid_coverage_ahead call in road_stream.gd's get_stats, which needs the game's
# GDExtension, is replaced by 0.0) headless under refgen/ring_harness.gd, which drives their _process_body/_schedule/
# _upload over the steps of test_ring_streamer.cpp and prints the jobs, uploads, tiles and known sets as C++ rows.
# Usage: extract_ring_ref.sh <racing_game checkout> <out ring_pins.inc> [godot binary]
set -euo pipefail
GAME="$1"
OUT="$2"
GODOT="${3:-godot}"
REV=5a3baed
HERE="$(cd "$(dirname "$0")" && pwd)"
show() { git -C "$GAME" show "$REV:$1"; }
PROJ="$(mktemp -d)"
trap 'rm -rf "$PROJ"' EXIT
mkdir -p "$PROJ/scripts" "$PROJ/shaders"
printf 'config_version=5\n[application]\nconfig/name="ring_ref"\n' > "$PROJ/project.godot"
show game/scripts/road_stream.gd | sed 's/^\(\s*var ahead := \).*RgRenderFocus\.grid_coverage_ahead.*/\10.0/' > "$PROJ/scripts/road_stream.gd"
show game/scripts/building_stream.gd > "$PROJ/scripts/building_stream.gd"
show game/scripts/frame_probe.gd > "$PROJ/scripts/frame_probe.gd"
show game/shaders/road.gdshader > "$PROJ/shaders/road.gdshader"
cp "$HERE/ring_harness.gd" "$PROJ/ring_harness.gd"
{
  echo "// Generated by tests/world/refgen/extract_ring_ref.sh: racing_game $REV's road_stream.gd and building_stream.gd"
  echo "// run headless under refgen/ring_harness.gd. Do not edit. {product, step, kind, x, y, a, b, c, value}"
  echo "// product 0 = road ribbons, 1 = buildings; kind 'J' job (a full, value order), 'U' upload (a full, b content),"
  echo "// 'T' resident tile after the step (a full, b near visible, c far visible), 'K' known (a full)."
  "$GODOT" --headless --path "$PROJ" --script res://ring_harness.gd 2>/dev/null | grep '^{'
} > "$OUT"
